def get_translation(key, language="en"):
    """
    Return the requested translation.

    Supported languages:
        en = English
        mr = Marathi
    """

    if language not in SUPPORTED_LANGUAGES:
        language = "en"

    # Exact key lookup first.
    value = TRANSLATIONS.get(key)

    # Support case-insensitive key lookup for older templates.
    if value is None:
        lower_key = str(key).lower()

        for existing_key, existing_value in TRANSLATIONS.items():
            if existing_key.lower() == lower_key:
                value = existing_value
                break

    if isinstance(value, dict):
        return value.get(
            language,
            value.get("en", key)
        )

    if value is not None:
        return value

    # Avoid displaying blank text for missing keys.
    return key


def get_translated_text(key, language="en"):
    """Compatibility helper for templates or existing Python code."""
    return get_translation(key, language)

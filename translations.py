def get_translation(key, language="en"):
    """Return the translation for English or Marathi."""
    if language not in SUPPORTED_LANGUAGES:
        language = "en"

    translation = TRANSLATIONS.get(key)

    if translation is None:
        normalized_key = str(key).strip().lower()
        for existing_key, existing_translation in TRANSLATIONS.items():
            if str(existing_key).strip().lower() == normalized_key:
                translation = existing_translation
                break

    if isinstance(translation, dict):
        return translation.get(language, translation.get("en", key))

    if translation is not None:
        return translation

    # Keep missing keys visible for easy identification.
    return key


def get_translated_text(key, language="en"):
    """Compatibility helper for modules using this function name."""
    return get_translation(key, language)
